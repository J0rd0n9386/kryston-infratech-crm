  const DICT = { en: {}, hi: {}, hinglish: {} };
  for (const row of ROWS) {
    const [key, english, hindi, hinglish] = row;
    DICT.en[key] = english;
    DICT.hi[key] = hindi === undefined || hindi === '' ? english : hindi;
    DICT.hinglish[key] = hinglish === undefined || hinglish === '' ? english : hinglish;
  }

  function readStoredLocale() {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (stored && LOCALES.some((entry) => entry.code === stored)) return stored;
    } catch {
      /* storage can be unavailable in private mode */
    }
    return 'en';
  }

  let current = readStoredLocale();

  function localeMeta(code = current) {
    return LOCALES.find((entry) => entry.code === code) || LOCALES[0];
  }

  function interpolate(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, (match, name) =>
      vars[name] === undefined || vars[name] === null ? match : String(vars[name]),
    );
  }

  function t(key, vars) {
    if (!key) return '';
    const table = DICT[current] || DICT.en;
    let text = table[key];
    if (text === undefined) text = DICT.en[key];
    if (text === undefined) return String(key);
    return interpolate(text, vars);
  }

  function tp(count, oneKey, manyKey, vars) {
    return t(Number(count) === 1 ? oneKey : manyKey, { count, ...(vars || {}) });
  }

  /**
   * Translate a raw database value (stage, status, department, role, task type)
   * and fall back to a readable version of the raw value when no row exists.
   */
  function label(prefix, value) {
    if (!value) return '—';
    const key = `${prefix}.${value}`;
    const table = DICT[current] || DICT.en;
    if (table[key] !== undefined) return table[key];
    if (DICT.en[key] !== undefined) return DICT.en[key];
    return String(value).replace(/_/g, ' ').replace(/\b\w/g, (letter) => letter.toUpperCase());
  }

  function applyStaticText(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      node.setAttribute('placeholder', t(node.dataset.i18nPlaceholder));
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((node) => {
      node.setAttribute('aria-label', t(node.dataset.i18nAria));
    });
    root.querySelectorAll('[data-i18n-title]').forEach((node) => {
      node.setAttribute('title', t(node.dataset.i18nTitle));
    });
  }

  function setLocale(code, { silent = false } = {}) {
    if (!LOCALES.some((entry) => entry.code === code)) return current;
    current = code;
    try {
      window.localStorage.setItem(STORAGE_KEY, code);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = localeMeta(code).htmlLang;
    applyStaticText(document);
    document.querySelectorAll('[data-locale]').forEach((button) => {
      const active = button.dataset.locale === code;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
    const labelNode = document.getElementById('langLabel');
    if (labelNode) labelNode.textContent = localeMeta(code).short;
    if (typeof KRY.onLocaleChange === 'function') KRY.onLocaleChange(code);
    if (!silent && typeof KRY.toast === 'function') KRY.toast(t('common.languageChanged'), 'success');
    return current;
  }

  Object.assign(KRY, {
    LOCALES,
    t,
    tp,
    label,
    locale: () => current,
    localeMeta,
    setLocale,
    applyStaticText,
    dateLocale: () => localeMeta().dateLocale,
    stageLabel: (value) => label('stage', value),
    statusLabel: (value) => label('status', value),
    priorityLabel: (value) => label('priority', value),
    taskTypeLabel: (value) => label('taskType', value),
    deptLabel: (value) => label('dept', value),
    roleLabel: (value) => label('role', value),
  });
